"""Regenerate src/data/plan.ts from scripts/plan.md (the exported plan document)."""
import re, json, datetime as dt, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
s = (root / "scripts" / "plan.md").read_text()

def table(seg):
    rows = [[c.strip() for c in l.strip().strip("|").split("|")] for l in seg.strip().split("\n")]
    return [dict(zip(rows[0], r)) for r in rows[2:]]

def table_after(label):
    i = s.index(label)
    return table(s[i:].split("\n\n", 2)[1])

data = {
    "measurements": table_after("**Measurements**"),
    "kitA": table_after("**Family A:"), "kitB": table_after("**Family B:"),
    "kitC": table_after("**Family C:"), "kitD": table_after("**Family D:"),
    "heroes": table(s[s.index("## Unique hero features"):].split("\n\n")[2]),
    "assetKitHeroes": table_after("**Kit and heroes**"),
    "props": table_after("**Props and debris**"),
    "foliage": table_after("**Foliage**\n"),
    "decals": table_after("**Decal sets**"),
    "materials": table_after("**Tiling materials"),
}
weeks = []
start = dt.date(2026, 10, 19)  # Monday of week 1; work days Mon, Tue, Fri, Sat, Sun
for m in re.finditer(r"^### Week (\d+) · (.+?) · (.+)$\n\n((?:- \[ \].*\n?)+)", s, flags=re.M):
    n = int(m.group(1)); mon = start + dt.timedelta(days=7 * (n - 1))
    dates = [mon + dt.timedelta(days=k) for k in (0, 1, 4, 5, 6)]
    days = []
    for j, line in enumerate(m.group(4).strip().split("\n")):
        txt = re.match(r"- \[ \] \*\*(.+?)\*\* · (.*)$", line).group(2)
        done = None
        if "*Done when:*" in txt:
            txt, done = [x.strip() for x in txt.split("*Done when:*")]
        days.append({"id": f"w{n}d{j+1}", "date": dates[j].isoformat(), "task": txt, "doneWhen": done,
                     "buffer": txt.startswith("Buffer"), "review": "Review " in txt})
    weeks.append({"n": n, "range": m.group(2), "title": m.group(3), "days": days})
assert len(weeks) == 15
data["weeks"] = weeks
out = ["// Generated by scripts/gen_plan_data.py from scripts/plan.md.",
       "export type Row = Record<string, string>;",
       "export type Day = { id: string; date: string; task: string; doneWhen: string | null; buffer: boolean; review: boolean };",
       "export type Week = { n: number; range: string; title: string; days: Day[] };", ""]
for k, v in data.items():
    out.append(f"export const {k}: {'Week[]' if k == 'weeks' else 'Row[]'} = {json.dumps(v, ensure_ascii=False, indent=1)};\n")
(root / "src" / "data" / "plan.ts").write_text("\n".join(out))
print("ok", sum(len(w["days"]) for w in weeks), "days")
