"""Regenerate src/data/curriculum.ts from scripts/curriculum.md (the Blender curriculum's daily lessons)."""
import re, json, datetime as dt, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
s = (root / "scripts" / "curriculum.md").read_text()
start = dt.date(2026, 10, 19)  # same calendar as the Mill Alley plan: Mon, Tue, Fri, Sat, Sun
weeks = []
for m in re.finditer(r"^### Week (\d+) · (.+?) · (.+)$\n\n((?:- \[ \].*\n?)+)", s, flags=re.M):
    n = int(m.group(1)); mon = start + dt.timedelta(days=7 * (n - 1))
    dates = [mon + dt.timedelta(days=k) for k in (0, 1, 4, 5, 6)]
    lessons = []
    for j, line in enumerate(m.group(4).strip().split("\n")):
        txt = re.match(r"- \[ \] \*\*(.+?)\*\* · (.*)$", line).group(2)
        parts = {"lesson": txt, "drill": None, "feeds": None, "standard": None}
        for key, label in [("standard", "*Standard check:*"), ("feeds", "*Feeds:*"), ("drill", "*Drill:*")]:
            if label in parts["lesson"]:
                parts["lesson"], parts[key] = [x.strip() for x in parts["lesson"].split(label, 1)]
        # a Standard check may sit after Feeds
        if parts["feeds"] and "*Standard check:*" in parts["feeds"]:
            parts["feeds"], parts["standard"] = [x.strip() for x in parts["feeds"].split("*Standard check:*", 1)]
        if parts["drill"] and "*Feeds:*" in parts["drill"]:
            parts["drill"], parts["feeds"] = [x.strip() for x in parts["drill"].split("*Feeds:*", 1)]
        lesson = parts["lesson"].removeprefix("Lesson: ")
        lessons.append({"id": f"c{n}d{j+1}", "date": dates[j].isoformat(), "lesson": lesson,
                        "drill": parts["drill"], "feeds": parts["feeds"], "standard": parts["standard"],
                        "buffer": lesson.startswith("Buffer")})
    weeks.append({"n": n, "range": m.group(2), "title": m.group(3), "lessons": lessons})
assert len(weeks) == 15 and sum(len(w["lessons"]) for w in weeks) == 75
out = ["// Generated by scripts/gen_curriculum_data.py from scripts/curriculum.md.",
       "export type Lesson = { id: string; date: string; lesson: string; drill: string | null; feeds: string | null; standard: string | null; buffer: boolean };",
       "export type CurriculumWeek = { n: number; range: string; title: string; lessons: Lesson[] };",
       "", f"export const curriculum: CurriculumWeek[] = {json.dumps(weeks, ensure_ascii=False, indent=1)};", ""]
(root / "src" / "data" / "curriculum.ts").write_text("\n".join(out))
print("ok", sum(len(w["lessons"]) for w in weeks), "lessons")
