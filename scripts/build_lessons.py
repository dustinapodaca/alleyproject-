"""Build the full Blender lessons from lessons/weekNN.md + verified resources in lessons/res_*.json.

Outputs
  lessons/out/Blender-Lessons.md        one Markdown file (headings: # week, ## lesson, ### section)
  lessons/out/weekNN.md                 the same, one file per week (for the online doc's week tabs)
  <repo>/src/data/lessons.ts            {id: {title, body}} for the tracker app
"""
import json, re, pathlib, sys

here = pathlib.Path(__file__).resolve().parent
src = here / "lessons"
out = src / "out"
out.mkdir(exist_ok=True)
repo = here.parent

res = {}
for f in sorted(src.glob("res_*.json")):
    for k, v in json.loads(f.read_text()).items():
        if not k.startswith("_") and isinstance(v, list):
            res.setdefault(k, []).extend(v)

LABEL = {"manual": "Manual", "video": "Video", "article": "Read", "ue5": "Unreal docs", "marmoset": "Marmoset docs"}
ORDER = {"video": 0, "article": 1, "manual": 2, "ue5": 3, "marmoset": 4}


BASE = "https://docs.blender.org/manual/en/latest/"
PATH = r"((?:\.\.\./)?[\w/.-]+?\.html(?:#[\w-]+)?)"


def linkify(note):
    """Turn manual paths in a note ('Mirror Modifier: modeling/...html', 'Bevel (.../edge/bevel.html)') into links."""
    prev = [""]

    def url(path):
        if path.startswith(".../"):
            rest = path[4:].split("/")
            segs = prev[0].split("/")
            cut = segs.index(rest[0]) if rest[0] in segs else len(segs) - 2
            path = "/".join(segs[:cut] + rest)
        prev[0] = path
        return BASE + path

    def a(m):
        lead, title, path = m.group(1) or "", m.group(2), m.group(3)
        return f"{lead}[{title}]({url(path)})"

    note = re.sub(r"(Also )?([A-Z0-9][\w-]*(?: [\w-]+){0,2}) \(" + PATH + r"\)", a, note)
    note = re.sub(r"(Also )?([A-Z0-9][\w-]*(?: [\w-]+){0,2}): " + PATH, a, note)
    note = re.sub(r"(?<![\w/:(.])([a-z][\w/.-]*?\.html(?:#[\w-]+)?)", lambda m: f"[manual page]({url(m.group(1))})" if "/" in m.group(1) else m.group(1), note)
    return note


def fmt_res(items):
    seen, lines = set(), []
    for r in sorted(items, key=lambda r: ORDER.get(r.get("kind"), 9)):
        if r["url"] in seen:
            continue
        seen.add(r["url"])
        label = LABEL.get(r.get("kind"), "Link")
        title = re.sub(r"\s*[(\-–|]+\s*Blender [\d.]+ LTS Manual\)?$", "", r["title"]).replace("[", "(").replace("]", ")")
        who = r.get("creator") or ""
        who = "" if who.lower().startswith(("blender manual", "blender foundation", "epic games", "marmoset")) else who
        note = linkify((r.get("note") or "").strip().rstrip("."))
        tail = " · ".join(x for x in [who, note] if x)
        lines.append(f"- **{label}:** [{title}]({r['url']})" + (f" — {tail}" if tail else ""))
    return "\n".join(lines)


missing, app, weeks_md = [], {}, []
for wf in sorted(src.glob("week*.md")):
    text = wf.read_text()
    parts = re.split(r"(?m)^### ", text)
    head, lessons = parts[0], parts[1:]
    week_out = [head.replace("## ", "# ", 1).rstrip() + "\n"]
    for block in lessons:
        title_line, body = block.split("\n", 1)
        m = re.search(r"<!-- id: (c\d+d\d) -->\n", body)
        lid = m.group(1)
        body = body.replace(m.group(0), "")
        key = title_line.split(" · ")[0]
        if "{{RES}}" in body:
            items = res.get(key, [])
            if not items:
                missing.append(key)
            body = body.replace("{{RES}}", fmt_res(items) or "- See the Blender Manual pages linked in Weeks 1 to 15's setup list.")
        body = body.strip() + "\n"
        app[lid] = {"title": title_line.split(" · ", 1)[1].strip(), "body": body}
        week_out.append("## " + title_line + "\n\n" + re.sub(r"(?m)^#### ", "### ", body))
    md = "\n".join(week_out)
    (out / wf.name).write_text(md)
    weeks_md.append(md)

intro = (here / "lessons_head.md").read_text() if (here / "lessons_head.md").exists() else ""
(out / "Blender-Lessons.md").write_text(intro + "\n\n".join(weeks_md))

ts = ["// Generated by scripts/build_lessons.py from scripts/lessons/*.md. Full text of every curriculum lesson.",
      "export type LessonText = { title: string; body: string };",
      f"export const lessonText: Record<string, LessonText> = {json.dumps(app, ensure_ascii=False, indent=1)};", ""]
(repo / "src" / "data" / "lessons.ts").write_text("\n".join(ts))
print(len(app), "lessons;", "missing resources:", missing or "none")
assert len(app) == 75
